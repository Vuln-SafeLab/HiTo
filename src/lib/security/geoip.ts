/** Convert "1.2.3.4" to 32-bit integer for fast table lookup. */
function ipv4ToInt(ip: string): number | null {
  const parts = ip.split(".");
  if (parts.length !== 4) return null;
  let n = 0;
  for (const p of parts) {
    const v = Number(p);
    if (!Number.isInteger(v) || v < 0 || v > 255) return null;
    n = (n * 256) + v;
  }
  return n >>> 0;
}

/** Find the country code for an IP via prefix matching (longest match wins). */
function ipToCountry(ip: string): string {
  // Try IPv4
  const num = ipv4ToInt(ip);
  if (num !== null) {
    let bestMatch: { prefix: string; cc: string } | null = null;
    for (const [cidr, cc] of IPV4_TO_COUNTRY) {
      if (cidr.includes(":")) continue; // skip IPv6
      const [base, bitsStr] = cidr.split("/");
      const bits = Number(bitsStr);
      if (!base || !Number.isFinite(bits)) continue;
      const baseNum = ipv4ToInt(base);
      if (baseNum === null) continue;
      const mask = bits === 0 ? 0 : (~0 << (32 - bits)) >>> 0;
      if ((num & mask) === (baseNum & mask)) {
        if (!bestMatch || cidr.split("/")[1]!.length > bestMatch.prefix.split("/")[1]!.length) {
          bestMatch = { prefix: cidr, cc };
        }
      }
    }
    if (bestMatch) return bestMatch.cc;
  }
  // IPv6: rough prefix match
  if (ip.includes(":")) {
    const lower = ip.toLowerCase();
    for (const [cidr, cc] of IPV4_TO_COUNTRY) {
      if (!cidr.includes(":")) continue;
      const prefix = cidr.split("/")[0]!.toLowerCase();
      if (lower.startsWith(prefix)) return cc;
    }
  }
  return "ZZ"; // Unknown
}

/** Look up the country for a string IP, returning ISO code or null. */
export function lookupCountryCode(ip: string): string | null {
  if (!ip || ip === "direct" || ip.startsWith("cc:")) return null;
  const cc = ipToCountry(ip);
  return cc === "ZZ" ? null : cc;
}

/** Convert geo coords (lat, lng in degrees) to equirectangular SVG coords. */
export function geoToSvg(
  lng: number,
  lat: number,
  width: number,
  height: number,
): [number, number] {
  const x = ((lng + 180) / 360) * width;
  const y = ((90 - lat) / 180) * height;
  return [x, y];
}
